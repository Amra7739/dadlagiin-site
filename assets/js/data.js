// LocalStorage Keys - Bump to v2 so newly added 56 internships load immediately
const STORAGE_KEYS = {
  INTERNSHIPS: "dadlaga_internships_data_v2",
  SAVED_JOBS: "dadlaga_saved_jobs_v1",
  APPLICATIONS: "dadlaga_user_applications_v1"
};

function getStoredInternships() {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.INTERNSHIPS);
    if (!raw) {
      localStorage.setItem(STORAGE_KEYS.INTERNSHIPS, JSON.stringify(INITIAL_INTERNSHIPS));
      return INITIAL_INTERNSHIPS;
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0 || !parsed[0] || !parsed[0].title) {
      localStorage.setItem(STORAGE_KEYS.INTERNSHIPS, JSON.stringify(INITIAL_INTERNSHIPS));
      return INITIAL_INTERNSHIPS;
    }
    return parsed.filter(j => j && j.title);
  } catch (e) {
    return INITIAL_INTERNSHIPS;
  }
}

function saveNewInternship(item) {
  const current = getStoredInternships();
  current.unshift(item);
  localStorage.setItem(STORAGE_KEYS.INTERNSHIPS, JSON.stringify(current));
  return current;
}

function getSavedJobIds() {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.SAVED_JOBS);
    return raw ? JSON.parse(raw) : [];
  } catch (e) {
    return [];
  }
}

function toggleSavedJobId(id) {
  let saved = getSavedJobIds();
  const index = saved.indexOf(id);
  let isSaved = false;
  if (index > -1) {
    saved.splice(index, 1);
    isSaved = false;
  } else {
    saved.push(id);
    isSaved = true;
  }
  localStorage.setItem(STORAGE_KEYS.SAVED_JOBS, JSON.stringify(saved));
  return isSaved;
}

function recordApplication(appData) {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.APPLICATIONS);
    const list = raw ? JSON.parse(raw) : [];
    list.unshift({ ...appData, submittedAt: new Date().toISOString() });
    localStorage.setItem(STORAGE_KEYS.APPLICATIONS, JSON.stringify(list));
    return true;
  } catch (e) {
    return false;
  }
}
